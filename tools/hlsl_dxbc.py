#!/usr/bin/env python3
"""HLSL -> DXBC for the D3D11 RHI backend (src/render/CMakeLists.txt runs it at build time) and the launcher's D3D11
renderer (launcher/CMakeLists.txt), in place of the Windows SDK's fxc. Standard library only (ctypes).

    python tools/hlsl_dxbc.py --profile vs_5_0 --entry vs_main --name kGsDrawVS --out gs_draw_vs.h
                              [-D NAME=VALUE ...] [--d3dcompiler DLL] [--check-fxc FXC] SOURCE.hlsl

It calls D3DCompile in d3dcompiler_47.dll - the compiler fxc itself runs, and part of every Windows 10 / 11
(System32) - with fxc's flags for `fxc /O3 /T <profile> /E <entry> /D ...`, so a build needs no Windows SDK
(DECISIONS.md 2026-11-03). Includes resolve next to the source, as fxc's do.

The header holds `const BYTE <name>[]`, as fxc's `/Fh /Vn <name>` (the code including it has <windows.h>).

--check-fxc FXC also compiles the shader with that fxc and fails when the two DXBC blobs differ (the SDK's fxc may
bring a newer d3dcompiler than System32's): CMake's VCS_DXBC_CHECK_FXC passes it for every shader.
"""
import argparse
import ctypes
import os
import subprocess
import sys
import tempfile

D3DCOMPILE_OPTIMIZATION_LEVEL3 = 1 << 15  # fxc /O3
D3D_COMPILE_STANDARD_FILE_INCLUDE = 1     # (ID3DInclude *)1: includes relative to the source's folder


class ShaderMacro(ctypes.Structure):
    _fields_ = [("name", ctypes.c_char_p), ("definition", ctypes.c_char_p)]


def blob_bytes(blob):
    """The contents of an ID3DBlob (then released): vtable slots 2 Release, 3 GetBufferPointer, 4 GetBufferSize."""
    vtable = ctypes.cast(blob, ctypes.POINTER(ctypes.POINTER(ctypes.c_void_p))).contents
    method = lambda slot, restype: ctypes.WINFUNCTYPE(restype, ctypes.c_void_p)(vtable[slot])
    data = ctypes.string_at(method(3, ctypes.c_void_p)(blob), method(4, ctypes.c_size_t)(blob))
    method(2, ctypes.c_ulong)(blob)
    return data


def compile_dxbc(dll, source, entry, profile, defines):
    """DXBC of `entry` in `source`, or exits with the compiler's messages."""
    d3d = ctypes.WinDLL(dll)
    fn = d3d.D3DCompile
    fn.restype = ctypes.c_long
    fn.argtypes = [ctypes.c_void_p, ctypes.c_size_t, ctypes.c_char_p, ctypes.POINTER(ShaderMacro), ctypes.c_void_p,
                   ctypes.c_char_p, ctypes.c_char_p, ctypes.c_uint, ctypes.c_uint, ctypes.POINTER(ctypes.c_void_p),
                   ctypes.POINTER(ctypes.c_void_p)]
    with open(source, "rb") as f:
        text = f.read()
    macros = (ShaderMacro * (len(defines) + 1))()
    for i, d in enumerate(defines):
        name, _, value = d.partition("=")
        macros[i] = ShaderMacro(name.encode(), (value or "1").encode())  # fxc's /D NAME is NAME=1
    code, errors = ctypes.c_void_p(), ctypes.c_void_p()
    hr = fn(text, len(text), os.path.abspath(source).encode("mbcs"), macros, D3D_COMPILE_STANDARD_FILE_INCLUDE,
            entry.encode(), profile.encode(), D3DCOMPILE_OPTIMIZATION_LEVEL3, 0, ctypes.byref(code), ctypes.byref(errors))
    messages = blob_bytes(errors).decode("utf-8", "replace") if errors.value else ""
    if hr < 0 or not code.value:
        sys.stderr.write(messages)
        sys.exit("hlsl_dxbc: D3DCompile failed on %s %s (0x%08x)" % (source, entry, hr & 0xFFFFFFFF))
    return blob_bytes(code)


def fxc_dxbc(fxc, source, entry, profile, defines, folder):
    fd, out = tempfile.mkstemp(suffix=".dxbc", dir=folder)
    os.close(fd)
    try:
        cmd = [fxc, "/nologo", "/O3", "/T", profile, "/E", entry, "/Fo", out]
        for d in defines:
            cmd += ["/D", d]
        result = subprocess.run(cmd + [source], capture_output=True, text=True)
        if result.returncode != 0:
            sys.stderr.write(result.stdout + result.stderr)
            sys.exit("hlsl_dxbc: fxc failed on %s %s" % (source, entry))
        with open(out, "rb") as f:
            return f.read()
    finally:
        os.remove(out)


def write_header(path, name, data, source, entry):
    lines = ["// Generated by tools/hlsl_dxbc.py from %s (%s) - do not edit." % (os.path.basename(source), entry),
             "#pragma once", "const BYTE %s[] = {" % name]
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 24]) + ",")
    lines.append("};")
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    os.replace(tmp, path)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--profile", required=True, help="vs_5_0, ps_4_0, ...")
    ap.add_argument("--entry", required=True)
    ap.add_argument("--name", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("-D", dest="defines", action="append", default=[])
    ap.add_argument("--d3dcompiler", default=os.path.join(os.environ.get("SystemRoot", r"C:\Windows"), "System32",
                                                          "d3dcompiler_47.dll"))
    ap.add_argument("--check-fxc", metavar="FXC", help="fail when this fxc's DXBC differs")
    ap.add_argument("source")
    a = ap.parse_args()

    data = compile_dxbc(a.d3dcompiler, a.source, a.entry, a.profile, a.defines)
    if a.check_fxc:
        reference = fxc_dxbc(a.check_fxc, a.source, a.entry, a.profile, a.defines,
                             os.path.dirname(os.path.abspath(a.out)))
        if reference != data:
            first = next((i for i, (x, y) in enumerate(zip(data, reference)) if x != y), min(len(data), len(reference)))
            sys.exit("hlsl_dxbc: %s %s differs from fxc's: %d vs %d bytes, first difference at byte %d"
                     % (a.source, a.entry, len(data), len(reference), first))
    write_header(a.out, a.name, data, a.source, a.entry)


if __name__ == "__main__":
    main()
