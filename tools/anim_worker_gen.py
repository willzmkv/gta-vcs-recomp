#!/usr/bin/env python3
"""Worker copies of the game's per-node animation code, for the native animation update (src/game/vcs_anim.cpp).

The node loop of the clump animation update (FUN_00401ad8) calls one of three per-node callbacks (FUN_00155068
quaternion + translation, FUN_00155c08 matrix, FUN_001552f8 root motion only); with what they call - keyframe sampling,
slerp, half-float decoding, sinf / acosf - they only read guest memory and write the clump's own node frames and node
states. This tool copies those recompiled functions out of generated/ee into one C++ file that can run off the game
thread on a context of its own: each direct call becomes a plain C++ call (no dispatch through the runtime, no EE
clock), the scheduler checkpoints on backward branches are dropped. Everything else - every instruction, the same
macros and float helpers - is the generated code as it is, so the copies compute bit for bit what the game does.

It refuses (exit 1, nothing written) when the call graph from the callbacks reaches anything that is not plain code:
an indirect call or jump, a syscall, a stub, a call to the runtime other than the two above. The output is game code:
it goes to generated/ (never committed), made again whenever generated/ee changes (CMakeLists.txt runs this at
configure time).

    python tools/anim_worker_gen.py [GENERATED_EE] [OUT.cpp]
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROOTS = (0x155068, 0x155C08, 0x1552F8)

DIRECT = re.compile(
    r'runtime->dispatchGuestBranch\(rdram, ctx, 0x([0-9A-Fa-f]+)u, 0x[0-9A-Fa-f]+u, 0x([0-9A-Fa-f]+)u, '
    r'PS2Runtime::GuestBranchKind::DirectCall, "JAL"\)')
CHECKPOINT = re.compile(r'runtime->eeCheckpointDue\([^)]*\)')
DEFINITION = re.compile(r'PS2_GUEST_CC void (\w+)\(uint8_t\* rdram, R5900Context\*(?: __restrict)? ctx, PS2Runtime \*runtime\)')
# the host's libm stubs the float code reaches (Kernel/Stubs/LibC.cpp): pure - the host's sinf / cosf on the context's
# registers; rem_pio2f writes its two results through its pointer argument (the caller's stack: the worker's own)
PURE_STUBS = re.compile(r'ps2_stubs::(__kernel_cosf|__kernel_sinf|__ieee754_rem_pio2f)\(rdram, ctx, runtime\);')
# what may stay: the runtime pointer handed to the memory / float macros, the unlisted-resume report, the strict
# return diagnostics compiled out
ALLOWED_RUNTIME = re.compile(r'runtime->dispatchGuestBranch\(rdram, ctx, jumpTarget, 0x[0-9A-Fa-f]+u, 0u, '
                             r'PS2Runtime::GuestBranchKind::Return, "JR \$ra"\)')


def find_file(ee, addr):
    suffix = "_0x%x.cpp" % addr
    for name in os.listdir(ee):
        if name.lower().endswith(suffix):
            return os.path.join(ee, name)
    return None


def body_problems(text):
    """What in a function's text is not plain code once the direct calls and checkpoints are rewritten."""
    rest = DIRECT.sub("", text)
    rest = CHECKPOINT.sub("", rest)
    rest = ALLOWED_RUNTIME.sub("", rest)
    rest = PURE_STUBS.sub("", rest)
    problems = []
    for m in re.finditer(r'runtime->(\w+)', rest):
        problems.append("runtime->" + m.group(1))
    for word in ("IndirectCall", "IndirectJump", "GuestBranchKind::Jump", "ps2_syscalls::", "ps2_stubs::", "SYSCALL",
                 "callSyscall", "handleSyscall"):
        if word in rest:
            problems.append(word)
    return sorted(set(problems))


def main():
    ee = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "generated", "ee")
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, "generated", "anim", "anim_worker.cpp")
    texts, order, todo, bad = {}, [], list(ROOTS), []
    while todo:
        addr = todo.pop()
        if addr in texts:
            continue
        path = find_file(ee, addr)
        if not path:
            bad.append("0x%x: no generated file" % addr)
            texts[addr] = ""
            continue
        with open(path, encoding="utf-8") as f:
            text = f.read()
        texts[addr] = text
        order.append(addr)
        defs = DEFINITION.findall(text)
        if len(defs) != 1:
            bad.append("0x%x: %d function definitions in %s" % (addr, len(defs), os.path.basename(path)))
        for p in body_problems(text):
            bad.append("0x%x: %s" % (addr, p))
        for m in DIRECT.finditer(text):
            todo.append(int(m.group(1), 16))
    if bad:
        print("[anim_worker_gen] not plain code - nothing written:\n  " + "\n  ".join(bad))
        return 1

    order.sort()
    names = {a: "W_%06X" % a for a in order}
    lines = [
        "// Generated by tools/anim_worker_gen.py from generated/ee: worker copies of the animation node code (game code -",
        "// never committed). Direct calls are plain C++ calls; checkpoints dropped; everything else as recompiled.",
        "#include \"ps2_runtime_macros.h\"",
        "#include \"ps2_runtime.h\"",
        "#include <ps2_recompiled_functions.h>",
        "#include <ps2_recompiled_stubs.h>",
        "#include \"ps2_syscalls.h\"",
        "#include \"ps2_stubs.h\"",
        "",
        "namespace vcs_anim_worker",
        "{",
        "using Fn = void (*)(uint8_t *, R5900Context *__restrict, PS2Runtime *);",
    ]
    for a in order:
        lines.append("static void %s(uint8_t* rdram, R5900Context* __restrict ctx, PS2Runtime *runtime);" % names[a])
    lines += [
        "// a JAL: the callee runs to its JR $ra (ctx->pc = $ra) - the runtime's dispatch, without the table and the clock",
        "static inline bool call(Fn fn, uint32_t target, uint32_t ret, uint8_t *rdram, R5900Context *ctx, PS2Runtime *runtime)",
        "{",
        "    ctx->pc = target;",
        "    fn(rdram, ctx, runtime);",
        "    if (ctx->pc == target)",
        "        ctx->pc = ret;",
        "    return ctx->pc == ret;",
        "}",
        "",
    ]
    for a in order:
        text = texts[a]
        start = DEFINITION.search(text)
        body = text[start.start():]
        body = DEFINITION.sub("static void %s(uint8_t* rdram, R5900Context* __restrict ctx, PS2Runtime *runtime)" % names[a],
                              body, count=1)
        body = DIRECT.sub(lambda m: "call(%s, 0x%sU, 0x%sU, rdram, ctx, runtime)" % (
            names[int(m.group(1), 16)], m.group(1).upper(), m.group(2).upper()), body)
        body = CHECKPOINT.sub("false", body)
        body = re.sub(r'PS_LOG_ENTRY\("[^"]*"\);', "", body)
        lines.append("// 0x%x" % a)
        lines.append(body.rstrip())
        lines.append("")
    lines += [
        "} // namespace vcs_anim_worker",
        "",
        "// the per-node callbacks by guest address (0: not one of them)",
        "vcs_anim_worker::Fn vcsAnimWorkerCallback(uint32_t address)",
        "{",
        "    switch (address)",
        "    {",
    ]
    for a in ROOTS:
        lines.append("    case 0x%XU: return vcs_anim_worker::%s;" % (a, names[a]))
    lines += ["    default: return nullptr;", "    }", "}", ""]
    os.makedirs(os.path.dirname(out), exist_ok=True)
    data = "\n".join(lines)
    if os.path.isfile(out):
        with open(out, encoding="utf-8") as f:
            if f.read() == data:
                print("[anim_worker_gen] %d functions, unchanged: %s" % (len(order), out))
                return 0
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(data)
    print("[anim_worker_gen] %d functions -> %s" % (len(order), out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
